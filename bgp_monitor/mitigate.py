"""Automated mitigation: generate prefix-list filter entries (IOS-style
text config) that drop anomalous announcements."""

from __future__ import annotations

from .analyze import Analysis

_HEADER = """\
! =====================================================================
! Auto-generated BGP mitigation filters
! Generated by bgp-hijack-monitor -- apply to the border ingress policy
! ====================================================================="""


def generate_filters(analyses: list[Analysis]) -> str:
    """Build a prefix-list config denying every anomalous announcement."""
    lines: list[str] = [_HEADER]
    seq = 10
    bad = [a for a in analyses if a.verdict != "VALID" and a.update.msg_type == "announce"]
    if not bad:
        lines.append("! No anomalous announcements -- no filters required.")
    for a in bad:
        upd = a.update
        for finding in a.findings:
            lines.append(f"! {a.verdict}: {finding.detail}")
        lines.append(f"! prefix {upd.prefix} announced by origin AS{upd.origin_as} via peer AS{upd.peer_as}")
        lines.append(f"ip prefix-list PL-BGP-MITIGATION seq {seq} deny {upd.prefix} le 32")
        seq += 10
    lines.append(f"ip prefix-list PL-BGP-MITIGATION seq {seq} permit 0.0.0.0/0 le 32")
    return "\n".join(lines) + "\n"
